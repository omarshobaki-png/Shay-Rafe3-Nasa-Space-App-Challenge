"""Bold display font for titles and big numbers, drawn in code.

    python tools/art/gen_ui_font.py [preview.png]

Writes art/font_display.png + art/font_display.fnt (BMFont text format, same as art/font.fnt).
Glyphs: capitals, digits and . , : ; ! ? % $ / + - = ( ) ' " & < > _ ; lower-case letters point at the
capitals. Face 9 x 11 px with 3 px stems and 2 px bars, plus a 1 px darker lower edge under every
stroke (grey in the texture, so it becomes a darker shade of whatever colour the text is drawn in).
Native size 12 (line height 13); draw it at 12, 24 or 36 only.
"""
import pathlib

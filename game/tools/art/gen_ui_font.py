def bitmap(rows):
    """Face rows -> 12-row grey array: 255 face, EDGE under every stroke, 0 empty."""
    w = len(rows[0])
    a = np.zeros((FACE_H + 1, w), np.uint8)
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == "#":
                a[y, x] = 255
    face = a == 255
    under = np.zeros_like(face)
    under[1:, :] = face[:-1, :]
    a[under & ~face] = EDGE
    return a


def build():
    order = sorted(G.keys(), key=ord)
    atlas_w, pad = 256, 1
    x, y, row_h = pad, pad, FACE_H + 1
    atlas = np.zeros((64, atlas_w, 4), np.uint8)
    lines = []
    for ch in order:
        bm = bitmap(G[ch])
        w = bm.shape[1]
        if x + w + pad > atlas_w:
            x, y = pad, y + row_h + pad
        atlas[y:y + row_h, x:x + w, 0:3] = bm[:, :, None]
        atlas[y:y + row_h, x:x + w, 3] = np.where(bm > 0, 255, 0)
        ids = [ord(ch)]
        if ch.isalpha():
            ids.append(ord(ch.lower()))
        for i in ids:
            lines.append("char id=%d x=%d y=%d width=%d height=%d xoffset=0 yoffset=0 xadvance=%d page=0 chnl=15" % (i, x, y, w, row_h, w + 1))
        x += w + pad
    used_h = y + row_h + pad
    assert used_h <= 64
    Image.fromarray(atlas, "RGBA").save(ART / "font_display.png")
    head = [
        'info face="SMD Display" size=12 bold=1 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=0 padding=0,0,0,0 spacing=1,1 outline=0',
        "common lineHeight=13 base=11 scaleW=256 scaleH=64 pages=1 packed=0 alphaChnl=0 redChnl=4 greenChnl=4 blueChnl=4",
        'page id=0 file="font_display.png"',
        "chars count=%d" % (len(lines) + 1),
        "char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance=5 page=0 chnl=15",
    ]
    (ART / "font_display.fnt").write_text("\n".join(head + lines) + "\n", encoding="ascii")
    return len(lines) + 1


def preview(path):
    """Sample lines at 1x and 2x on the panel colour, shown at 3x."""
    def draw(dst, text, x0, y0, col, scale):
        x = x0
        for ch in text.upper():
            if ch == " ":
                x += 5 * scale
                continue
            bm = bitmap(G[ch])
            for (yy, xx), v in np.ndenumerate(bm):
                if v:
                    c = [k * int(v) // 255 for k in col]
                    for sy in range(scale):
                        for sx in range(scale):
                            py, px = y0 + yy * scale + sy, x + xx * scale + sx
                            if v and dst[py + scale, px + scale].sum() == 20 + 26 + 46:
                                dst[py + scale, px + scale] = (3, 4, 8)   # drop shadow
                            dst[py, px] = c
            x += (bm.shape[1] + 1) * scale
    img = np.zeros((150, 420, 3), np.uint8)
    img[:] = (20, 26, 46)
    draw(img, "ABCDEFGHIJKLMNOPQRSTUVWXYZ", 4, 4, (255, 215, 94), 1)
    draw(img, "0123456789 .,:;!?%$/+-=()'\"&<>_", 4, 20, (232, 236, 255), 1)
    draw(img, "MISSION LOG   RESOURCES   $266M", 4, 36, (79, 214, 255), 1)
    draw(img, "SPACE MISSION DESIGNER", 4, 54, (255, 215, 94), 2)
    draw(img, "PARTIAL SUCCESS 60%", 4, 84, (109, 255, 138), 2)
    draw(img, "ALT 3,504 KG  T+11 S", 4, 114, (232, 236, 255), 2)
    im = Image.fromarray(img, "RGB")
    im.resize((im.width * 3, im.height * 3), Image.NEAREST).save(path)


if __name__ == "__main__":
    n = build()
    print("font_display: %d chars" % n)
    if len(sys.argv) > 1:
        preview(sys.argv[1])
        print("preview", sys.argv[1])

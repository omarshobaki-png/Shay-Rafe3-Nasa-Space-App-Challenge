import numpy as np
from PIL import Image

ART = pathlib.Path(__file__).resolve().parents[2] / "art"
FACE_H = 11
EDGE = 150  # grey level of the lower edge (face is 255)

G = {}


def glyph(ch, rows):
    rows = [r for r in rows.strip("\n").split("\n")]
    assert len(rows) == FACE_H, (ch, len(rows))
    w = len(rows[0])
    assert all(len(r) == w for r in rows), ch
    G[ch] = rows


def rows_of(n, row):
    return "\n".join([row] * n)


